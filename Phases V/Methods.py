#upper() - Capital Letters
name = "Akash"
print(name.upper())

#lower() — Small Letters
name = "AKASH"
print(name.lower())


#strip() — Extra Spaces Remove
name = "   Akash   "
print(name.strip())


#find() — Character/Text Search
name = "Akash"
print(name.find("a"))

name = "Akash Rathore"

print(name.startswith("Akash"))

name = "Akash Rathore"

print(name.endswith("Rathore"))



